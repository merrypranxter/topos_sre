const ADJECTIVE_ISH =
  /ly$|ous$|ful$|less$|ish$|ive$|al$|ic$|able$|ible$|ent$|ant$/i;

export function looksLikeModifier(token: string): boolean {
  if (token.length < 3) return false;
  return ADJECTIVE_ISH.test(token);
}

export function containsForbidden(text: string): string[] {
  const lower = text.toLowerCase();
  return FORBIDDEN_TOKENS.filter((t) => new RegExp(`\\b${t}\\b`, "i").test(lower));
}
